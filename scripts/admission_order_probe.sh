#!/usr/bin/env bash
# Rebuild the two per-database admission designs verbatim and run the SAME
# admission-order experiment against both, so the claim in
# docs/evidence/steady-starvation-evidence.log is reproducible in one command.
#
#   OLD  a96f261  the phase-fair design that was replaced
#   NEW  HEAD     the shipped ticket lock
#
# The queues are EXTRACTED from git, not retyped: a mismatch between this
# file and the committed source would silently invalidate the result, and
# "the harness drifted" is the failure mode that produced the unreproducible
# numbers this script exists to prevent. Each design is wrapped in a module
# that exposes two harness-only helpers; the helpers are the ONLY non-verbatim
# code, and they are one line each.
#
# The experiment is the in-repo test
# src/store.rs::admission_follows_queue_order_not_a_race: a guard is already
# held, one writer queues behind it, the writer is confirmed to hold a ticket,
# then READERS_BEHIND readers queue behind the writer. When the held guard
# drops, every admitted acquirer stamps a single monotonic counter, and a
# trial is lost if any reader is stamped before the writer -- a reader that
# arrived later being served first.
#
# Measured on the replaced design at load1 78-80 (16 cores, shared rig):
#   1 reader behind the writer : 0 / 300 trials lost   <- the old "guard" shape
#   3 readers                  : 4, 7, 6 per 100
#   8 readers (READ_PERMITS)   : 28, 34, 30 per 100
# and 0 / 300 on the shipped design at every size. One reader is not enough:
# a condvar wakes waiters in the order they blocked, so a lone reader loses
# the state mutex to the writer it overtook. A batch is what the old design
# hands the queue to at a phase refresh.
#
# Usage: scripts/admission_order_probe.sh [rounds] [readers_behind]
# Exit 0 = the shipped design lost no trial, which is the invariant its
# in-repo test asserts. Exit 1 = the shipped design lost a trial: STOP, that
# is a real regression and the numbers above no longer apply.

set -euo pipefail

ROUNDS="${1:-3}"
READERS_BEHIND="${2:-8}"
OLD_COMMIT="${OLD_COMMIT:-a96f261}"
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

extract() { # <file> -> the queue block only
    # Two rules rather than one alternation: the two designs are introduced
    # by different doc comments, and a range expression with `|` is not
    # portable across awk implementations.
    awk '
        /^\/\/\/ Per-database admission queue state\.$/ { start = 1 }
        /^\/\/\/ A per-database admission queue: the shared\/exclusive guard plus the$/ { start = 1 }
        /^\/\/\/ Per-database admission-queue waits since boot\./ { if (start) exit }
        start { print }
    ' "$1" > "$2"
    if ! grep -q 'struct QueueState' "$2" || ! grep -q 'fn acquire' "$2"; then
        echo "extraction failed for $1 (markers moved); refusing to guess" >&2
        exit 2
    fi
}

git -C "$REPO" show "$OLD_COMMIT:src/store.rs" > "$WORK/old.rs"
git -C "$REPO" show "HEAD:src/store.rs" > "$WORK/new.rs"
extract "$WORK/old.rs" "$WORK/old_queue.rs"
extract "$WORK/new.rs" "$WORK/new_queue.rs"

{
    cat <<'HEADER'
// GENERATED by scripts/admission_order_probe.sh -- do not edit.
// The two queue bodies below are extracted verbatim from git by that script;
// everything outside `mod` blocks is the experiment.
#![allow(dead_code, unused_imports, unused_variables)]
use std::collections::BTreeSet;
use std::sync::atomic::{AtomicUsize, Ordering as Seq};
use std::sync::{Arc, Condvar, Mutex, MutexGuard};
use std::thread;
use std::time::{Duration, Instant};

const ACQUIRE_TIMEOUT: Duration = Duration::from_millis(500);

#[derive(Debug, Clone, Copy)]
enum Error { Internal, Busy }
impl Error {
    fn internal() -> Self { Error::Internal }
    fn busy() -> Self { Error::Busy }
}
// the crate's own alias, which the extracted code is written against
type Result<T> = std::result::Result<T, Error>;

mod old {
    use super::*;
    // harness-only shims: the design's own field names, one line each
    pub fn admit(q: &Arc<AdmissionQueue>, write: bool) -> Result<AdmissionGuard> {
        AdmissionQueue::acquire(q, write)
    }
    pub fn writer_queued(q: &Arc<AdmissionQueue>) -> bool {
        q.state.lock().map(|s| s.writer_serving < s.writer_next).unwrap_or(false)
    }
HEADER
    cat "$WORK/old_queue.rs"
    cat <<'MID'
}

mod new {
    use super::*;
    // harness-only shims: the design's own field names, one line each
    pub fn admit(q: &Arc<AdmissionQueue>, write: bool) -> Result<AdmissionGuard> {
        AdmissionQueue::acquire(q, write)
    }
    pub fn writer_queued(q: &Arc<AdmissionQueue>) -> bool {
        q.state.lock().map(|s| !s.waiting_writers.is_empty()).unwrap_or(false)
    }
MID
    cat "$WORK/new_queue.rs"
    cat <<'TAIL'
}

/// One trial, generic over the two designs. Returns the number of readers
/// stamped before the writer.
fn trial<Q, G, Admit, Queued>(
    admit: Admit,
    queued: Queued,
    readers_behind: usize,
    trial: usize,
) -> usize
where
    Admit: Fn(&Arc<Q>, bool) -> Result<G> + Send + Sync + Copy + 'static,
    G: Send + 'static,
    Q: Make + Send + Sync + 'static,
    Queued: Fn(&Arc<Q>) -> bool,
{
    let queue: Arc<Q> = Arc::new(Q::make());
    let held = admit(&queue, false).expect("held guard");
    let stamp = Arc::new(AtomicUsize::new(0));
    let writer_at = Arc::new(AtomicUsize::new(usize::MAX));

    let (qw, sw, aw) = (queue.clone(), stamp.clone(), writer_at.clone());
    let writer = thread::spawn(move || {
        if let Ok(guard) = admit(&qw, true) {
            aw.store(sw.fetch_add(1, Seq::SeqCst), Seq::SeqCst);
            drop(guard);
        }
    });

    // Only queue readers once the writer provably holds a ticket, so "queued
    // first" is not itself a race.
    let held_ticket = (0..500).any(|_| {
        if queued(&queue) { true } else { thread::sleep(Duration::from_millis(1)); false }
    });
    assert!(held_ticket, "trial {trial}: writer never queued");

    let mut readers = Vec::new();
    for _ in 0..readers_behind {
        let (qr, sr, ar) = (queue.clone(), stamp.clone(), Arc::new(AtomicUsize::new(usize::MAX)));
        let stamp_slot = ar.clone();
        readers.push((ar, thread::spawn(move || {
            if let Ok(guard) = admit(&qr, false) {
                stamp_slot.store(sr.fetch_add(1, Seq::SeqCst), Seq::SeqCst);
                drop(guard);
            }
        })));
    }

    drop(held);
    writer.join().unwrap();
    let writer_slot = writer_at.load(Seq::SeqCst);
    let mut first_ahead = 0;
    for (at, reader) in readers {
        reader.join().unwrap();
        if at.load(Seq::SeqCst) < writer_slot { first_ahead += 1; }
    }
    first_ahead
}

trait Make { fn make() -> Self; }
impl Make for old::AdmissionQueue { fn make() -> Self { Self::default() } }
impl Make for new::AdmissionQueue { fn make() -> Self { Self::default() } }

const TRIALS: usize = 100;

fn main() {
    let readers_behind: usize = std::env::args().nth(2).and_then(|s| s.parse().ok()).unwrap_or(8);
    println!("# load1 at start: {}", std::fs::read_to_string("/proc/loadavg")
        .map(|s| s.split_whitespace().next().unwrap_or("?").to_string())
        .unwrap_or_else(|_| "?".into()));
    println!("# {TRIALS} trials per shape, readers behind the writer: {readers_behind}");
    let mut shipped_losses = 0;
    for round in 1..=std::env::args().nth(1).and_then(|s| s.parse().ok()).unwrap_or(3) {
        let old_lost = (0..TRIALS)
            .map(|t| trial(old::admit, old::writer_queued, readers_behind, t))
            .filter(|n| *n > 0).count();
        let new_lost = (0..TRIALS)
            .map(|t| trial(new::admit, new::writer_queued, readers_behind, t))
            .filter(|n| *n > 0).count();
        shipped_losses += new_lost;
        println!("round {round}: old phase design {old_lost}/{TRIALS} trials lost | shipped ticket lock {new_lost}/{TRIALS}");
    }
    if shipped_losses > 0 {
        eprintln!("REGRESSION: the shipped design lost {shipped_losses} trials; queue order is no longer structural");
        std::process::exit(1);
    }
    println!("shipped design: 0 trials lost, as its in-repo test asserts");
}
TAIL
} > "$WORK/probe.rs"

rustc -O -o "$WORK/probe" "$WORK/probe.rs"
"$WORK/probe" "$ROUNDS" "$READERS_BEHIND"
